// GetCountryByPhone 通过手机号码获取国家信息
func GetCountryByPhone(phoneNumber string) []CountryInfo {
	// 清理手机号码，移除非数字字符
	cleanPhone := cleanPhoneNumber(phoneNumber)

	if len(cleanPhone) < 2 {
		return nil
	}

	// 尝试不同的区号长度匹配
	for length := 4; length >= 1; length-- {
		if len(cleanPhone) >= length {
			codeStr := cleanPhone[:length]
			if code, err := strconv.Atoi(codeStr); err == nil {
				if countries, exists := phoneCodeMap[code]; exists {
					return countries
				}
			}
		}
	}

	return nil
}

// GetCountryByCode 通过区号直接获取国家信息
func GetCountryByCode(code int) []CountryInfo {
	if countries, exists := phoneCodeMap[code]; exists {
		return countries
	}
	return nil
}

// GetAllCountries 获取所有国家信息，按区号排序
func GetAllCountries() []CountryInfo {
	var allCountries []CountryInfo

	// 获取所有区号并排序
	var codes []int
	for code := range phoneCodeMap {
		codes = append(codes, code)
	}
	sort.Ints(codes)

	// 按区号顺序添加国家信息
	for _, code := range codes {
		countries := phoneCodeMap[code]
		allCountries = append(allCountries, countries...)
	}

	return allCountries
}

// SearchCountryByName 通过国家名称搜索
func SearchCountryByName(name string) []CountryInfo {
	var results []CountryInfo
	name = strings.ToLower(strings.TrimSpace(name))

	for _, countries := range phoneCodeMap {
		for _, country := range countries {
			if strings.Contains(strings.ToLower(country.CountryName), name) {
				results = append(results, country)
			}
		}
	}

	return results
}

// cleanPhoneNumber 清理手机号码，只保留数字
func cleanPhoneNumber(phone string) string {
	// 移除所有非数字字符
	reg := regexp.MustCompile(`[^0-9]`)
	return reg.ReplaceAllString(phone, "")
}

// IsValidPhoneFormat 检查手机号码格式是否有效
func IsValidPhoneFormat(phone string) bool {
	cleanPhone := cleanPhoneNumber(phone)
	return len(cleanPhone) >= 7 && len(cleanPhone) <= 15
}
